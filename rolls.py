def get_hero_quote(roll_value: float) -> str:
    """Returns a hero quote for ANY roll value in the format: 🪶Кестрель, Нелётная ярость 🗣️ ..."""
    if roll_value > 0:
        quote = random.choice(HERO_QUOTES["positive"])
        hero = "🪶Кестрель, Нелётная ярость"
    elif roll_value < 0:
        quote = random.choice(HERO_QUOTES["negative"])
        hero = "🔨Рейгор Каменное Копыто"
    else:
        quote = random.choice(HERO_QUOTES["neutral"])
        if random.random() < 0.5:
            hero = "🪶Кестрель, Нелётная ярость"
        else:
            hero = "🔨Рейгор Каменное Копыто"

    return f"{hero} 🗣️{quote}"


def apply_fissure_protection(current_fissure: float, roll: float, is_fatal: bool) -> ProtectionResult:
    """Applies protection for small fissures on fatal rolls"""
    if is_fatal and current_fissure < 5:
        reduced_roll = max(-5, roll)
        protection_msg = f"🛡 УРОН СНИЖЕН! Было {roll}, теперь {reduced_roll}"
        return reduced_roll, protection_msg

    return roll, ""


def calculate_new_fissure(current_fissure: float, roll: float) -> float:
    """Calculates new fissure size with minimum 0.1"""
    new_value = current_fissure + roll
    return max(0.1, new_value)


def calculate_streak_bonus(current_win_streak: int, base_roll: float) -> tuple[float, str]:
    """Streak bonus: +1cm per win streak applied only to positive rolls."""
    if current_win_streak > 0 and base_roll > 0:
        streak_bonus = current_win_streak
        new_roll = base_roll + streak_bonus
        streak_text = f"🔥 СТРИК x{current_win_streak}: +{streak_bonus} см."
        return new_roll, streak_text
    return base_roll, ""



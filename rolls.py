def calculate_fissure_roll(current_fissure: float) -> RollResult:
    """
    Calculates new roll based on current fissure size.
    Returns: RollResult = (roll_value, message, is_fatal, got_help)
    
    AZARDNAYA FORMULA:
    - Symmetric range for true balance (50/50 positive/negative)
    - Spread scales with fissure for dramatic swings
    - Small fissure protection (can't lose more than you have)
    - Fatal threshold: <= -10
    - Zero roll remapped to ±1 for excitement
    """
    spread = min(50, max(5, int(current_fissure * 0.35)))
    
    negative_max = -spread
    positive_max = spread
    
    if current_fissure < 10:
        negative_max = -max(1, min(spread, int(current_fissure)))
    
    roll = random.randint(negative_max, positive_max)
    
    if roll == 0:
        roll = random.choice([-1, 1])
    
    is_fatal = roll <= FATAL_ROLL
    return roll, "", is_fatal, False


